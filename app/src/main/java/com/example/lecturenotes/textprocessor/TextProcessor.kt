package com.example.lecturenotes.textprocessor

/**
 * КОНТРАКТ МОДУЛЯ: TextProcessor
 *
 * Обрабатывает сырой текст из Whisper и применяет:
 * 1. Замену голосовых команд на символы ("плюс" → "+")
 * 2. Вычисление арифметических выражений ("2 + 2" → "2 + 2 (=4)")
 * 3. Нормализацию пунктуации и пробелов
 *
 * USB-ПРИНЦИП:
 * UI и ViewModel не знают, какая реализация внутри.
 * Можно подменить на LLM-структуратор, на пустую заглушку, на тестовый мок.
 *
 * ИНТЕГРАЦИЯ:
 * Вызывается ПОСЛЕ WhisperTranscriber.processChunk() и ПЕРЕД сохранением в Room.
 * Потокобезопасен: не хранит mutable state между вызовами.
 */
interface TextProcessor {

    /**
     * Главная точка входа.
     * Принимает сырой распознанный текст, возвращает обработанный.
     *
     * @param rawText — текст из Whisper (может быть пустым, может содержать мусор)
     * @return обработанный текст. Если rawText blank — возвращает его как есть.
     */
    fun process(rawText: String): String

    /**
     * Только замена голосовых команд.
     * Полезно если нужно применить команды без математики (например, в preview).
     */
    fun applyVoiceCommands(text: String): String

    /**
     * Только вычисление арифметики.
     * Полезно для отладки или если команды уже применены.
     */
    fun solveArithmetic(text: String): String

    /**
     * Конфигурация: словарь голосовых команд.
     * Ключ — фраза (lowercase), значение — замена.
     * Immutable snapshot текущих команд.
     */
    val voiceCommands: Map<String, String>
}